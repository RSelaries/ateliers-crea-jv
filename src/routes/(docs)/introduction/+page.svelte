<h1>Ateliers création de jeux-vidéo</h1>

<p>Ce site est la documentation des ateliers de création de jeux-vidéo organisés par Sirius Productions et La Sierra Prod.</p>
<p>Ces ateliers ont pour but de vous apprendre les bases du développement de jeux-vidéo pour ensuite organiser une gamejam.</p>

<h2>Qu'est-ce qu'une gamejam ?</h2>

<p>Une gamejam est un événement de création de jeux-vidéo ou de jeux de société en un temps limité (24h, 48h, une semaine...).</p>
<p>Les gamejams permettent de développer des idées de jeu novatrices, certains jeux indépendants ont d'ailleurs commencé en tant que projets de gamejam (Celeste, SuperHot, Baba is You, Inscryption...).</p>
<p>Les gamejams sont des évènements très ouverts, de nombreuses personnes participent à leur première gamejam sans avoir jamais créé de jeu. Tout le monde est le bienvenu et peut participer à son échelle: musique, dessins, idées de jeu... il y a toujours quelque chose à apporter.</p>

<h2>Où et quand ?</h2>

<p>Premier atelier le vendredi 15 mai!</p>
<p>Les ateliers vont prendre place un vendredi sur deux, de 19h à 22h au CiNey.</p>

<h2>Quels outils on va utiliser ?</h2>

Voici la liste des outils que l'on va utiliser pendant ces ateliers.
(Je fais ici une liste de tous les outils utiles pour le gamedev, nous n'aurons peut-être pas le temps de tous les utiliser mais vous pouvez aller les voir si vous êtes intéressés)
Logo Godot
Godot

Godot est un moteur de jeu gratuit et open source. C'est le logiciel que l'on va le plus utiliser.
Blender Godot
Blender

Blender est un logiciel de modélisation 3D gratuit et open source. On va l'utiliser pour créer les objets et personages (les meshs) de nos jeux en 3D.
Blockbench Logo
Blockbench

Blockbench est un logiciel gratuit et open-source de modélisation 3D simplifié. Il sert initialement à modéliser des personnages et blocks pour Minecraft et Hytale mais peut aussi être utilisé pour faire des modèles en low-poly et pixel art.
Pixelorama Logo
Pixelorama

Pixelorama est un logiciel de pixel art gratuit et open source. On pourra l'utiliser pour créer les sprites pour nos jeux 2D.

    Pixelorama a été développé avec le moteur Godot !
