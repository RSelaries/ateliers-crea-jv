<h1 id="introduction">Ateliers découverte du gamedev</h1>
<p>
    Ce site est la documentation des ateliers de découverte du game-developement animés par
    <ExternalLink href="https://rselaries.github.io/portfolio">Raphaël Selaries</ExternalLink>
    pour <ExternalLink href="https://sirius-productions.fr/accueil/">Sirius Productions</ExternalLink>.
</p>
<p>
    Ces ateliers ont pour but de faire découvrir le <b>developpement de jeux vidéo</b>
    indépendant et professionnel. Mais également d'apprendre à développer des jeux vidéo en utilisant
    le moteur de jeu <ExternalLink href="https://godotengine.org/fr/">Godot</ExternalLink>.
</p>

<h2 id="commencer-a-creer">Je veux créer un jeu !</h2>
<p>
    Vous pouvez commencer dès maintenant en suivant le premier atelier:
    <Link href="ateliers/devine-le-nombre">Devine le nombre</Link>.
    <br>Sinon, vous pouvez suivre le <ExternalLink href="https://docs.godotengine.org/fr/4.x/getting_started/step_by_step/index.html">tutoriel officiel de Godot</ExternalLink>.
</p>

<h2 id="participer-aux-ateliers">Je veux participer aux ateliers</h2>
